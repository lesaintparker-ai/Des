import { pipeline, env } from '@huggingface/transformers';
import fs from 'fs';
env.localModelPath = './node_modules/sts-whisper-small/models/';
env.allowRemoteModels = false;
const asr = await pipeline('automatic-speech-recognition', 'Xenova/whisper-small', { dtype: 'q8' });
const buf = fs.readFileSync('voice.f32');
const audio = new Float32Array(buf.buffer, buf.byteOffset, buf.length/4);
const mode = process.argv[2] === 'word' ? 'word' : true;
const out = await asr(audio, { language: 'french', task: 'transcribe', return_timestamps: mode, chunk_length_s: 30, stride_length_s: 5 });
console.log(JSON.stringify(out, null, 0));
